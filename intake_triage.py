"""Decide whether a new incoming email is a support request before anything answers it.

Three kinds of mail reach a support address without being support: bulk promotions, mail that
websites generate by themselves (form notifications, plugin alerts), and messages people meant
for another business. The assessment reads the original headers, which a hosted help desk never
exposed to its rules, together with the message shape and the sender's history. It returns the
evidence for each verdict so a person can check it.

`assess` is pure: callers supply the parsed message and what the mailbox knows about the sender.
"""

import json
import re

CATEGORIES = ("support", "promotion", "site_mail", "bounce", "auto_reply", "wrong_address")
ACTIONABLE = ("promotion", "site_mail", "bounce", "auto_reply")  # May be filed without a person.

# Headers that only bulk-mail services add. A mailing list such as Google Groups rewrites the
# generic List-* headers of everything it forwards, so those count only when they point elsewhere.
BULK_HEADERS = (
    "x-mailchimp-id", "x-mc-user", "x-campaign", "x-campaignid", "x-campaign-id",
    "x-sg-eid", "x-sg-id", "x-mailgun-sid", "x-mailgun-tag", "x-mailgun-variables", "x-mailjet-campaign",
    "x-mj-mid", "x-sib-id", "x-mailin-campaign", "x-klaviyo-message-id", "x-kmail-account", "x-hs-cid",
    "x-hubspot-tracking", "x-csa-complaints", "x-report-abuse", "x-report-abuse-to", "x-mailer-recptid",
    "x-ac-campaign", "x-cm-message-id", "x-drip-id", "x-mailerlite", "x-ml-campaign", "x-constant-contact",
    "x-roving-id", "x-emarsys", "x-sfmc-stack", "x-mandrill-user", "x-sendgrid-eid",
    "x-lemlist-id", "x-woodpecker", "x-instantly", "x-mailshake", "x-smartlead",
)
BULK_MAILERS = re.compile(
    r"mailchimp|sendgrid|mailgun|sendinblue|brevo|klaviyo|hubspot|activecampaign|campaign ?monitor|"
    r"constant ?contact|mailerlite|mailjet|salesforce|marketo|customer\.?io|lemlist|woodpecker|"
    r"instantly|mailshake|smartlead|apollo|outreach\.io|sendpulse|getresponse|aweber|moosend|omnisend",
    re.I,
)
# Mail providers add these to personal mail as well, so alone they prove nothing.
WEAK_BULK_HEADERS = ("feedback-id",)
# What a forwarding list writes into every message it passes on: its own unsubscribe notice and
# archive links. Removed before the text is read, or every message would look like a newsletter.
# (Found on the first live message, 24 November 2026: the list's footer and its
# List-Unsubscribe-Post header had been counted as the sender's.)
LIST_FOOTER = re.compile(
    r"(?is)(?:--\s*)?you received this message because you are subscribed to the google groups.*\Z|"
    r"to unsubscribe from this group and stop receiving e-?mails from it[^\n]*(?:\n[^\n]*){0,2}|"
    r"to view this discussion (?:on the web )?visit\s+https://groups\.google\.com\S*|"
    r"for more options,? visit\s+https://groups\.google\.com\S*"
)
# Mail composed by a website rather than by a person at a mail client.
SITE_HEADERS = (
    "x-php-originating-script", "x-php-script", "x-wpcf7-content-type", "x-wp-mail-smtp",
    "x-wpforms", "x-mailer-wordpress", "x-gravity-forms", "x-formidable", "x-ninja-forms",
)
SITE_MAILERS = re.compile(r"phpmailer|wpmailsmtp|wp mail smtp|wordpress|swiftmailer|symfony mailer|post smtp|fluentsmtp|easy wp smtp", re.I)
SITE_SUBJECT = re.compile(
    r"^\s*\[[^\]]{2,80}\]|wordfence|new user registration|password (?:reset|changed)|"
    r"new (?:order|booking|reservation|submission|entry|comment|form|enquiry|inquiry)\b|"
    r"please moderate|site (?:health|recovery)|background update|plugin(?:s)? (?:were|was|have been) updated",
    re.I,
)
SITE_BODY = re.compile(
    r"sent from a contact form|this e-?mail was sent from (?:a|the|your)|sent via the contact form|"
    r"this message was sent from (?:a|the|your)|form submission from|submitted (?:on|from|via) (?:your|the) (?:web)?site|"
    r"formulaire de contact|formulario de contacto|kontaktformular|modulo di contatto|contactformulier|"
    r"this alert was generated by|you are receiving this (?:e-?mail|notification) because (?:you|your site)",
    re.I,
)
UNSUBSCRIBE = re.compile(
    r"unsubscribe|d[ée]sinscri|d[ée]sabonn|abbestellen|abmelden|darse de baja|cancelar (?:la |tu |su )?suscripci|"
    r"disiscriv|annulla(?:re)? l.iscrizione|uitschrijven|afmelden|avregistrer|dezabon|opt[- ]out|"
    r"manage (?:your )?(?:e-?mail |subscription )?preferences|e-?mail preferences|no longer (?:wish|want) to receive|"
    r"ne plus recevoir|stop receiving these",
    re.I,
)
VIEW_ONLINE = re.compile(
    r"view (?:this )?(?:e-?mail|message|newsletter) in (?:your |a )?(?:web )?browser|view (?:it )?online|"
    r"voir (?:ce message|la version|cet e-?mail) en ligne|im browser (?:an)?(?:sehen|zeigen)|"
    r"ver (?:este (?:correo|mensaje) )?en (?:el|tu|su) navegador|visualizza nel browser|bekijk (?:de )?online",
    re.I,
)
PITCH = re.compile(
    r"backlink|guest post|sponsored post|link (?:exchange|insertion|building)|seo (?:services|audit|agency)|"
    r"domain authority|collaboration proposal|paid collaboration|write for (?:you|your)|"
    r"increase (?:your )?(?:traffic|sales|ranking)|first page of google|web ?design (?:services|agency)|"
    r"lead generation|outsourc|virtual assistant|app development (?:services|company)",
    re.I,
)
BOUNCE_SUBJECT = re.compile(
    r"undeliver|delivery status notification|mail delivery (?:failed|subsystem|failure)|returned mail|"
    r"delivery (?:has )?failed|failure notice|message not delivered|non remis|unzustellbar|no se pudo entregar",
    re.I,
)
AUTO_SUBJECT = re.compile(
    r"out of (?:the )?office|automatic reply|auto(?:matic)?[- ]?(?:reply|response)|autoreply|abwesenheit|"
    r"r[ée]ponse automatique|respuesta autom[áa]tica|risposta automatica|afwezig|on (?:vacation|holiday|leave)",
    re.I,
)
REPLY_SUBJECT = re.compile(r"^\s*(?:re|aw|sv|antw|odp|rif|res)\s*(?:\[\d+\])?\s*:", re.I)
ROBOT_SENDER = re.compile(
    r"^(?:no[-_.]?reply|do[-_.]?not[-_.]?reply|newsletters?|news|marketing|promo(?:tions)?|offers?|"
    r"notifications?|mailer|bounces?|campaigns?|updates|digest|announce(?:ments)?)\b",
    re.I,
)
DAEMON_SENDER = re.compile(r"^(?:mailer-daemon|postmaster)$", re.I)
# Words a message about a website product uses and a note to a restaurant or shop does not.
TECH_WORDS = (
    "wordpress", "theme", "themes", "plugin", "plugins", "license", "licence", "customizer", "gutenberg",
    "woocommerce", "css", "widget", "widgets",
)
# Points at which a verdict counts as confident. Measured against answered conversations.
CONFIDENT = {"promotion": 4, "site_mail": 4, "bounce": 4, "auto_reply": 4}
WORD = re.compile(r"[^\W_]{3,40}", re.UNICODE)
TAGS = re.compile(r"<[^<>]*>")  # Linear on a body full of unclosed brackets.
READ_LIMIT = 200_000  # Characters of a message the check reads.


def header_names(msg):
    return {str(name).lower() for name in (msg.keys() if msg is not None else ())}


def first(msg, name):
    return str(msg.get(name, "") or "") if msg is not None else ""


def assess(msg, subject, body, author, *, own_domains=(), vocabulary=(), answered_before=False,
           contacts_before=0, replies_to_us=False):
    """Classify one new message. `msg` may be None when only stored content is available.

    answered_before: this sender already has a conversation that an agent answered.
    contacts_before: earlier conversations from this sender, answered or not.
    replies_to_us: the message references mail this mailbox sent.
    """
    names = header_names(msg)
    markup = (body or "")[:READ_LIMIT]
    subject = (subject or "")[:2000]
    text = LIST_FOOTER.sub(" ", TAGS.sub(" ", markup))
    lowered = text.casefold()
    local, _, domain = (author or "").casefold().partition("@")
    own = {d.casefold() for d in own_domains if d}
    ours = bool(domain) and (domain in own or any(domain.endswith("." + d) for d in own))
    reasons = {category: [] for category in CATEGORIES}
    score = dict.fromkeys(CATEGORIES, 0)
    kinds = {category: set() for category in CATEGORIES}

    def note(category, points, reason, kind="content"):
        score[category] += points
        reasons[category].append(reason)
        kinds[category].add(kind)

    # Delivery reports and automatic answers.
    if DAEMON_SENDER.fullmatch(local):
        note("bounce", 4, f"sent by {local}@")
    if "x-failed-recipients" in names:
        note("bounce", 4, "carries X-Failed-Recipients")
    if msg is not None and msg.get_content_type() == "multipart/report":
        note("bounce", 4, "is a delivery report")
    if BOUNCE_SUBJECT.search(subject or ""):
        note("bounce", 2, "subject reads as a delivery failure")
    auto = first(msg, "Auto-Submitted").strip().lower()
    if auto and auto != "no":
        note("auto_reply", 4, f"Auto-Submitted: {auto[:40]}")
    if names & {"x-autoreply", "x-autorespond", "x-autoresponder"} or first(msg, "Precedence").strip().lower() == "auto_reply":
        note("auto_reply", 4, "marked as an automatic reply")
    if AUTO_SUBJECT.search(subject or ""):
        note("auto_reply", 2, "subject reads as an automatic reply")

    # Mail generated by a website.
    mailer = first(msg, "X-Mailer") + " " + first(msg, "User-Agent")
    site_header = sorted(names & set(SITE_HEADERS))
    if site_header:
        note("site_mail", 4, "website mail header " + site_header[0], "sender")
    if SITE_MAILERS.search(mailer):
        note("site_mail", 3, "composed by " + SITE_MAILERS.search(mailer)[0], "sender")
    if local == "wordpress":
        note("site_mail", 3, "sent as wordpress@", "address")
    if SITE_BODY.search(text):
        note("site_mail", 3, "text says a website form sent it")
    if SITE_SUBJECT.search(subject or "") and score["site_mail"]:
        note("site_mail", 1, "subject reads as a site notification")

    # Bulk promotions.
    bulk = sorted(names & set(BULK_HEADERS))
    if bulk:
        note("promotion", 3, "bulk-mail header " + bulk[0], "sender")
        if len(bulk) > 1:
            note("promotion", 1, f"{len(bulk)} bulk-mail headers", "sender")
    weak = sorted(names & set(WEAK_BULK_HEADERS))
    if weak:
        note("promotion", 1, "relay header " + weak[0], "sender")
    if BULK_MAILERS.search(mailer):
        note("promotion", 3, "sent with " + BULK_MAILERS.search(mailer)[0], "sender")
    # A forwarding list replaces every List-* header and Precedence with its own, so on a
    # message that carries a List-Id none of them describes the original sender.
    listed = bool(first(msg, "List-Id").strip())
    unsubscribe = first(msg, "List-Unsubscribe").casefold()
    if (unsubscribe and not listed
            and not any(d in unsubscribe for d in (*own, "googlegroups.com", "groups.google.com"))):
        note("promotion", 2, "List-Unsubscribe points to the sender", "sender")
    if not listed and "list-unsubscribe-post" in names:
        note("promotion", 2, "one-click unsubscribe header", "sender")
    if not listed and first(msg, "Precedence").strip().lower() == "bulk":
        note("promotion", 2, "Precedence: bulk", "sender")
    links = len(re.findall(r"<a\s", markup, re.I))
    images = len(re.findall(r"<img\s", markup, re.I))
    if UNSUBSCRIBE.search(text):
        note("promotion", 2, "offers an unsubscribe link")
    if VIEW_ONLINE.search(text):
        note("promotion", 2, "offers a web version")
    if links >= 5 and (images >= 3 or "<table" in markup.casefold()):
        note("promotion", 1, f"newsletter layout ({links} links, {images} images)")
    if ROBOT_SENDER.match(local):
        note("promotion", 1, f"sent from {local}@", "address")
    if PITCH.search(text) or PITCH.search(subject or ""):
        note("promotion", 2, "reads as a sales pitch")

    # Signs of a real exchange with this mailbox take points away from every non-support verdict.
    words = set(WORD.findall(lowered)) | set(WORD.findall((subject or "").casefold()))
    product = sorted(words & ({w.casefold() for w in vocabulary} | set(TECH_WORDS)))
    machine = any(reasons[c] for c in ("promotion", "site_mail", "bounce", "auto_reply"))
    relief = 0
    if replies_to_us:
        relief += 4
    if answered_before:
        relief += 2
    if product:
        relief += 1
    for category in ("promotion", "site_mail"):
        if score[category]:
            score[category] -= relief
        # Mail from our own domains is ours, whatever sent it.
        if ours:
            score[category] = 0
            reasons[category] = []

    # A person writing to the wrong business: no machine traces, no history, nothing about our products.
    if (not machine and not ours and not product and not contacts_before and not replies_to_us
            and not REPLY_SUBJECT.search(subject or "") and len(text.strip()) >= 20):
        note("wrong_address", 2, "first message from this sender, and it names none of our products")
        if not answered_before and len(text) < 4000:
            note("wrong_address", 1, "short personal message")

    category = max(("bounce", "auto_reply", "site_mail", "promotion", "wrong_address"), key=lambda c: score[c])
    points = score[category]
    if points < 2:
        return {"category": "support", "confidence": "high" if not any(v > 0 for v in score.values()) else "medium",
                "score": 0, "reasons": [], "evidence": evidence(names, mailer, links, images, product)}
    if category == "wrong_address":
        confidence = "low"  # Meaning has to be read by a person or a model before anything is sent.
    else:
        bar = CONFIDENT[category]
        confidence = "high" if points >= bar else "medium" if points >= bar - 1 else "low"
        # What a message says is never enough to file it: the sending side has to agree.
        # Someone we answered before, or who replies to our mail, is only ever flagged.
        corroborated = category in ("bounce", "auto_reply") or len(kinds[category]) >= 2
        if confidence == "high" and (not corroborated or answered_before or replies_to_us):
            confidence = "medium"
    return {"category": category, "confidence": confidence, "score": points, "reasons": reasons[category],
            "evidence": evidence(names, mailer, links, images, product)}


def evidence(names, mailer, links, images, product):
    """Body-free facts kept with each verdict, for checking the rules against real mail."""
    kept = sorted(n for n in names if n.startswith(("x-", "list-", "feedback", "precedence", "auto-submitted")))
    return {"headers": kept[:60], "mailer": mailer.strip()[:120], "links": links, "images": images,
            "product_words": product[:12]}


def acts(verdict):
    """Only confident machine-mail verdicts may be filed away without a person."""
    return verdict["category"] in ACTIONABLE and verdict["confidence"] == "high"


# Mailbox integration. The transport calls these inside its own transaction.

FILED_TAGS = {
    "promotion": "promotion",
    "site_mail": "site-mail",
    "bounce": "delivery-report",
    "auto_reply": "auto-reply",
}
SUSPECT_TAG = "possible-wrong-address"
ANSWERED_TAG = "wrong-address"  # Set once the wrong-address reply went out.
# A conversation that was only flagged as a possible wrong address and then answered as support
# is ordinary history; only the confirmed tag marks the sender as a stranger.
NOT_CUSTOMER_TAGS = ("spammy", "spam", "non-support", "promotion", "site-mail", ANSWERED_TAG)


def mode():
    """off: no assessment. observe: record verdicts only. act: file confident machine mail."""
    import os

    value = os.environ.get("INBOX_TRIAGE_MODE", "observe").strip().lower()
    return value if value in ("off", "observe", "act") else "observe"


def holds_acknowledgment(verdict):
    """Whether a possible wrong address goes without the automatic acknowledgment.

    Off unless INBOX_TRIAGE_SUSPECT_ACK=hold: the flag is a guess, and a first-time customer
    who names no product should still hear that the message arrived.
    """
    import os

    return (verdict["category"] == "wrong_address"
            and os.environ.get("INBOX_TRIAGE_SUSPECT_ACK", "send").strip().lower() == "hold")


def schema(db):
    db.executescript("""
        CREATE TABLE IF NOT EXISTS intake_triage(object_key TEXT PRIMARY KEY, conversation INTEGER,
            category TEXT NOT NULL, confidence TEXT NOT NULL, score INTEGER NOT NULL, reasons TEXT NOT NULL,
            evidence TEXT NOT NULL, filed INTEGER NOT NULL DEFAULT 0, assessed TEXT NOT NULL);
        CREATE INDEX IF NOT EXISTS intake_triage_recent ON intake_triage(assessed DESC);
        CREATE INDEX IF NOT EXISTS intake_triage_conversation ON intake_triage(conversation);
    """)


def judge(db, msg, subject, body, author, refs):
    """Assess a message using what this mailbox knows about its sender."""
    import os

    import company

    customers = [row[0] for row in db.execute(
        "SELECT customer_id FROM customer_emails WHERE email=? LIMIT 8", (author,))]
    day_ago = db.execute("SELECT strftime('%Y-%m-%dT%H:%M:%S','now','-1 day')").fetchone()[0]
    contacts = answered = 0
    for customer in customers:
        for cid, tags, created in db.execute(
            "SELECT id,json_extract(data,'$.tags'),created FROM conversations WHERE customer_id=? "
            "ORDER BY id DESC LIMIT 40", (customer,),
        ).fetchall():
            try:
                named = {str(t.get("tag", "")).casefold() for t in json.loads(tags or "[]") if isinstance(t, dict)}
            except ValueError:
                named = set()
            # Someone who wrote to the wrong business before is still a stranger to us, so a
            # later misdirected message is recognised like the first. Within a day of the
            # last one it counts as history, which caps the wrong-address reply at one per
            # address per day whoever is writing under that address.
            if ANSWERED_TAG not in named or str(created or "") >= day_ago:
                contacts += 1
            if named & set(NOT_CUSTOMER_TAGS):
                continue
            if not answered and db.execute(
                "SELECT 1 FROM threads WHERE conversation_id=? AND json_extract(data,'$.type')='message' "
                "AND coalesce(json_extract(data,'$.state'),'published')='published' LIMIT 1", (cid,),
            ).fetchone():
                answered = 1
    replies = bool(refs) and db.execute(
        "SELECT 1 FROM json_each(?) ref JOIN mail_ids m ON m.mid=ref.value LIMIT 1",
        (json.dumps(list(refs)),),
    ).fetchone() is not None
    words = WORD.findall(os.environ.get("INBOX_PRODUCT_WORDS", "").casefold()) + WORD.findall(company.NAME.casefold())
    if db.execute("SELECT 1 FROM sqlite_master WHERE name='desk_products'").fetchone():
        for key, name in db.execute("SELECT id,name FROM desk_products"):
            words += WORD.findall((key + " " + name).casefold())
    own = [company.DOMAIN, company.GROUP_DOMAIN, *os.environ.get("INBOX_OWN_MAIL_DOMAINS", "").split()]
    return assess(msg, subject, body, author, own_domains=own, vocabulary=words,
                  answered_before=bool(answered), contacts_before=contacts, replies_to_us=replies)


def record(db, key, conversation, verdict, filed, when):
    db.execute(
        "INSERT INTO intake_triage VALUES(?,?,?,?,?,?,?,?,?) ON CONFLICT(object_key) DO UPDATE SET "
        "conversation=excluded.conversation,category=excluded.category,confidence=excluded.confidence,"
        "score=excluded.score,reasons=excluded.reasons,evidence=excluded.evidence,filed=excluded.filed,"
        "assessed=excluded.assessed",
        (key, conversation, verdict["category"], verdict["confidence"], verdict["score"],
         json.dumps(verdict["reasons"], ensure_ascii=False), json.dumps(verdict["evidence"], ensure_ascii=False),
         int(filed), when),
    )


def for_conversation(db, conversation):
    row = db.execute(
        "SELECT category,confidence,score,reasons,filed,assessed FROM intake_triage WHERE conversation=? "
        "ORDER BY assessed DESC LIMIT 1", (conversation,),
    ).fetchone()
    if not row:
        return None
    return {"category": row[0], "confidence": row[1], "score": row[2], "reasons": json.loads(row[3]),
            "filed": bool(row[4]), "assessed": row[5]}
